-- Medisent AI — demo reset (run BEFORE seed.sql). Removes everything a rehearsal created and
-- puts the seeded rows back to their seeded state; seed.sql then regenerates logs, refills and
-- alerts. Seeded ids: hospitals a…, staff b…, patients c…, platform admin d…, drugs e…,
-- prescriptions f…. Safe to run more than once. Nothing here touches real patient data: the
-- project only holds demo data.
begin;

-- ---------- rows created at rehearsals (not seeded prescriptions) ----------
delete from audit_log where target_table = 'prescriptions' and target_id not like 'f0000000-%';
delete from alerts where prescription_id in (select id from prescriptions where id::text not like 'f0000000-%');
delete from drug_checks;
delete from refills where prescription_id in (select id from prescriptions where id::text not like 'f0000000-%');
delete from dose_logs where reminder_id in (select id from reminders where prescription_id in (select id from prescriptions where id::text not like 'f0000000-%'));
delete from reminders where prescription_id in (select id from prescriptions where id::text not like 'f0000000-%');
delete from prescriptions where id::text not like 'f0000000-%';

-- ---------- seeded prescriptions back to their seeded state ----------
update prescriptions
   set stopped_early_at = null, interaction_reviewed_by = null, interaction_reviewed_at = null, active = true, patient_notified_at = null
 where id::text like 'f0000000-%';
-- The three patient entries wait for a pharmacist again.
update prescriptions
   set status = 'pending', verified_by = null, verified_at = null, rejection_reason = null
 where id in ('f0000000-0000-4000-8000-000000000101', 'f0000000-0000-4000-8000-000000000102', 'f0000000-0000-4000-8000-000000000103');
-- Reminders that an Edit deactivated and replaced: keep only the seeded set, active.
delete from reminders where prescription_id::text like 'f0000000-%' and active = false;
update reminders set active = true where prescription_id::text like 'f0000000-%';
-- Refills and alerts are regenerated by seed.sql.
delete from refills where prescription_id::text like 'f0000000-%';
delete from alerts;

-- ---------- accounts, sign-ups and hospitals created at rehearsals ----------
delete from otp_codes;
delete from signup_sessions;
delete from verification_attempts;
-- Profiles cascade from auth.users; anything not seeded (b… staff, c… patients, d… platform admin) goes.
delete from auth.users
 where id in (select id from profiles where id::text not like 'b0000000-%' and id::text not like 'c0000000-%' and id::text not like 'd0000000-%');
-- Hospitals registered during rehearsals (the two demo hospitals are a0000000-…).
delete from hospitals where id::text not like 'a0000000-%';

commit;
